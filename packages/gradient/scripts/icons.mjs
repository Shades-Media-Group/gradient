/**
 * Writes src/icons.ts from icons/*.svg and the brand list below.
 *
 * The interface set is Shades' own: one hand-drawn file per icon in icons/,
 * on a 24 × 24 grid, 2 px round strokes in currentColor. To add one, draw it
 * to those rules, save it as icons/<kebab-name>.svg and run `yarn icons`.
 * Marks of other services come from Simple Icons (CC0) and are filled.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const simple = dirname(require.resolve('simple-icons'))

/** Gradient name → Simple Icons file. Brand marks are for links to those services only. */
const BRANDS = {
  github: 'github',
  figma: 'figma',
  chrome: 'googlechrome',
  npm: 'npm',
  behance: 'behance',
  dribbble: 'dribbble',
  instagram: 'instagram',
  facebook: 'facebook',
  telegram: 'telegram',
  whatsapp: 'whatsapp',
  tiktok: 'tiktok',
  youtube: 'youtube',
  cloudflare: 'cloudflare',
}

const inner = (file) =>
  readFileSync(file, 'utf8')
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<title>.*?<\/title>/, '')
    .trim()

const line = (name, body) => `  ${name}: '${body.replaceAll("'", "\\'")}',`
const camel = (file) => file.replace(/\.svg$/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const ui = readdirSync(join(root, 'icons'))
  .filter((file) => file.endsWith('.svg'))
  .sort()
  .map((file) => line(camel(file), inner(join(root, 'icons', file))))
const brands = Object.entries(BRANDS).map(([name, file]) =>
  line(name, inner(join(simple, 'icons', `${file}.svg`))),
)

writeFileSync(
  join(root, 'src/icons.ts'),
  `// Generated by scripts/icons.mjs. Do not edit; change the list there and run \`yarn icons\`.
//
// Interface icons: Shades Icons, drawn for Gradient, MIT.
// Brand marks: Simple Icons, CC0. The marks belong to their owners; use them
// only to link to their services.

/** Shades interface icons: 24 × 24, 2 px round strokes in currentColor. */
export const icons = {
${ui.join('\n')}
} as const

/** Marks of other services: 24 × 24, filled in currentColor. */
export const brandIcons = {
${brands.join('\n')}
} as const
`,
)
console.log(`Wrote ${ui.length} interface icons and ${brands.length} brand marks`)
